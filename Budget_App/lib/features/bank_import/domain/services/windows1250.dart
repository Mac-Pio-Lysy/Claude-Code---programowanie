/// Decoder for the Windows-1250 ("Central European") single-byte encoding
/// still used by several Polish banks' CSV exports, since `dart:convert`
/// only ships UTF-8/Latin-1/ASCII out of the box.
///
/// Bytes 0x00-0x7F map 1:1 to ASCII/Unicode, same as Windows-1250 itself.
/// This table covers 0x80-0xFF (per the Unicode Consortium's CP1250.TXT);
/// unassigned code points in that range decode to U+FFFD.
abstract final class Windows1250 {
  static const int _replacementChar = 0xFFFD;

  static const List<int> _upperHalf = [
    0x20AC, _replacementChar, 0x201A, _replacementChar, // 0x80-0x83
    0x201E, 0x2026, 0x2020, 0x2021, // 0x84-0x87
    _replacementChar, 0x2030, 0x0160, 0x2039, // 0x88-0x8B
    0x015A, 0x0164, 0x017D, 0x0179, // 0x8C-0x8F
    _replacementChar, 0x2018, 0x2019, 0x201C, // 0x90-0x93
    0x201D, 0x2022, 0x2013, 0x2014, // 0x94-0x97
    _replacementChar, 0x2122, 0x0161, 0x203A, // 0x98-0x9B
    0x015B, 0x0165, 0x017E, 0x017A, // 0x9C-0x9F
    0x00A0, 0x02C7, 0x02D8, 0x0141, // 0xA0-0xA3
    0x00A4, 0x0104, 0x00A6, 0x00A7, // 0xA4-0xA7
    0x00A8, 0x00A9, 0x015E, 0x00AB, // 0xA8-0xAB
    0x00AC, 0x00AD, 0x00AE, 0x017B, // 0xAC-0xAF
    0x00B0, 0x00B1, 0x02DB, 0x0142, // 0xB0-0xB3
    0x00B4, 0x00B5, 0x00B6, 0x00B7, // 0xB4-0xB7
    0x00B8, 0x0105, 0x015F, 0x00BB, // 0xB8-0xBB
    0x013D, 0x02DD, 0x013E, 0x017C, // 0xBC-0xBF
    0x0154, 0x00C1, 0x00C2, 0x0102, // 0xC0-0xC3
    0x00C4, 0x0139, 0x0106, 0x00C7, // 0xC4-0xC7
    0x010C, 0x00C9, 0x0118, 0x00CB, // 0xC8-0xCB
    0x011A, 0x00CD, 0x00CE, 0x010E, // 0xCC-0xCF
    0x0110, 0x0143, 0x0147, 0x00D3, // 0xD0-0xD3
    0x00D4, 0x0150, 0x00D6, 0x00D7, // 0xD4-0xD7
    0x0158, 0x016E, 0x00DA, 0x0170, // 0xD8-0xDB
    0x00DC, 0x00DD, 0x0162, 0x00DF, // 0xDC-0xDF
    0x0155, 0x00E1, 0x00E2, 0x0103, // 0xE0-0xE3
    0x00E4, 0x013A, 0x0107, 0x00E7, // 0xE4-0xE7
    0x010D, 0x00E9, 0x0119, 0x00EB, // 0xE8-0xEB
    0x011B, 0x00ED, 0x00EE, 0x010F, // 0xEC-0xEF
    0x0111, 0x0144, 0x0148, 0x00F3, // 0xF0-0xF3
    0x00F4, 0x0151, 0x00F6, 0x00F7, // 0xF4-0xF7
    0x0159, 0x016F, 0x00FA, 0x0171, // 0xF8-0xFB
    0x00FC, 0x00FD, 0x0163, 0x02D9, // 0xFC-0xFF
  ];

  static String decode(List<int> bytes) {
    final buffer = StringBuffer();
    for (final byte in bytes) {
      if (byte < 0x80) {
        buffer.writeCharCode(byte);
      } else {
        buffer.writeCharCode(_upperHalf[byte - 0x80]);
      }
    }
    return buffer.toString();
  }
}
